const KEY = 'lb:lang';
const FALLBACK = 'en';
const SUPPORTED = Object.keys(I18N);

let CURRENT = null;

async function __lbNow() {
  let lang;
  try {
    const s = await chrome.storage.local.get(KEY);
    lang = s[KEY];
  } catch (e) {
    lang = undefined;
  }
  if (typeof lang !== 'string' || !SUPPORTED.includes(lang)) {
    lang = (typeof navigator !== 'undefined' && navigator.language ? navigator.language : 'en').toLowerCase().split('-')[0];
    if (!SUPPORTED.includes(lang)) lang = FALLBACK;
  }
  return lang;
}

function __lbDict(lang) {
  return I18N[lang] || I18N[FALLBACK];
}

function __lbT(key, lang, params) {
  const d = __lbDict(lang || CURRENT || FALLBACK);
  let v = d[key];
  if (typeof v !== 'string') v = I18N[FALLBACK][key] || key;
  if (params && typeof params === 'object') {
    for (const k of Object.keys(params)) v = v.split('{{' + k + '}}').join(String(params[k]));
  }
  return v;
}

async function __lbApply(root) {
  CURRENT = await __lbNow();
  const d = __lbDict(CURRENT);
  root = root || document;
  for (const el of root.querySelectorAll('[data-i18n], [data-i18n-title]')) {
    const k = el.getAttribute('data-i18n') || el.getAttribute('data-i18n-title');
    let v = d[k];
    if (typeof v !== 'string') v = I18N[FALLBACK][k] || k;
    const t = el.tagName.toLowerCase();
    if (t === 'input' || t === 'textarea') el.placeholder = v;
    else if (el.hasAttribute('data-i18n-title')) el.title = v;
    else el.textContent = v;
  }
  const langSel = root.querySelector('[data-i18n-lang]');
  if (langSel) {
    langSel.value = CURRENT;
    langSel.addEventListener('change', async () => {
      await chrome.storage.local.set({ [KEY]: langSel.value });
      await __lbApply(root);
    });
  }
  const title = root.querySelector('title');
  if (title && d.name) title.textContent = d.name;
  return d;
}

function __lbResolve(word, from, to) {
  const w = String(word || '').trim().toLowerCase();
  if (!w) return null;
  let base = null;
  let pivot = false;
  if (from === 'en' && w in EN_DICT) base = w;
  else if (from === 'es' && w in ES_INDEX) {
    base = ES_INDEX[w];
    pivot = from !== 'en';
  } else if (from === 'fr' && w in FR_INDEX) {
    base = FR_INDEX[w];
    pivot = from !== 'en';
  }
  if (!base) return null;
  const entry = EN_DICT[base];
  let out;
  if (to === 'en') out = entry.en;
  else if (to === 'es') out = entry.es;
  else if (to === 'fr') out = entry.fr;
  else out = null;
  if (!out) return null;
  return { word: w, base, out, pivot: pivot || from !== 'en' };
}

function __lbTranslate(word, from, to) {
  const r = __lbResolve(word, from, to);
  return r ? r.out : null;
}

function __lbPhrase(text, from, to) {
  const words = String(text || '').split(/\s+/).filter(Boolean);
  const out = [];
  let missing = 0;
  for (const w of words) {
    const r = __lbResolve(w, from, to);
    if (r) out.push(r.out);
    else {
      out.push(w);
      missing++;
    }
  }
  return { out: out.join(' '), missing, total: words.length };
}

function __lbDictSize() {
  return PAIRS.length;
}

function __lbWords(from) {
  if (from === 'es') return Object.keys(ES_INDEX);
  if (from === 'fr') return Object.keys(FR_INDEX);
  return Object.keys(EN_DICT);
}

